const HERO_SKILLS_BY_ID = new Map();
const HERO_SKILL_NAMES = new Map();
export function registerHeroSkillMetadata(entries) {
  entries=entries.filter(({hero})=>is_hero_in_release(hero));
  const pending = new Set();
  for (const {hero, skills} of entries) {
    if (!hero?.id || HERO_SKILLS_BY_ID.has(hero.id) || pending.has(hero.id) || !Array.isArray(skills)) throw new Error('Invalid or duplicate hero skill metadata ID');
    pending.add(hero.id);
  }
  for (const {hero, skills} of entries) {
    HERO_SKILLS_BY_ID.set(hero.id, Object.freeze([...skills]));
    for (const name of new Set([hero.name, hero.display_name, ...(hero.aliases || [])].filter(Boolean))) {
      if (!HERO_SKILL_NAMES.has(name)) HERO_SKILL_NAMES.set(name, new Set());
      HERO_SKILL_NAMES.get(name).add(hero.id);
    }
  }
}
registerHeroSkillMetadata([...CLASSIC_HEROES, ...EXPANSION_HEROES, ...SECOND_FOUR_HEROES].map(hero => ({hero, skills:HERO_SKILLS[hero.name] || []})));
export function skillsForHero(hero, {current=false} = {}) {
  const id=hero&&typeof hero==='object'?hero.id:hero;
  if(EXCLUDED_SPECIAL_HERO_IDS.includes(id)||['刘晔','王允','张奋'].includes(id))return [];
  if(Object.hasOwn(WANGYUN_HERO_SKILLS_BY_ID,id))return current ? wangyunSkillCardsForIds(hero?.skill_ids) : WANGYUN_HERO_SKILLS_BY_ID[id];
  if(Object.hasOwn(SGS_BASE_NEXT_SOURCE_SKILLS_BY_ID,id))return SGS_BASE_NEXT_SOURCE_SKILLS_BY_ID[id];
  const canonical=canonical_hero_for_source(id);
  if(canonical)return HERO_SKILLS_BY_ID.get(canonical.id)||[];
  if (HERO_SKILLS_BY_ID.has(id)) return HERO_SKILLS_BY_ID.get(id);
  const candidates=HERO_SKILL_NAMES.get(hero);
  const ids=new Set([...(candidates??[])].map(candidate=>canonical_hero_for_source(candidate)?.id??candidate));
  return ids.size===1?HERO_SKILLS_BY_ID.get(ids.values().next().value):[];
}
export function activeSkillMetadata(id, hero = null) {
  const matches = (hero ? skillsForHero(hero) : [...HERO_SKILLS_BY_ID.values()].flat()).filter(s => s.activeId === id);
  return matches.length === 1 ? matches[0] : null;
}

